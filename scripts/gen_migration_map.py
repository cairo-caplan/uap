"""
Generate `docs/migration-map.md`: entry-by-entry mapping of the old
per-project IP arrays (`ips/<project>.json`, deleted) to the new IP-centric
layout (`ips/<id>.json` + `projects/<project>.json`), with the human review
checklists the migration deferred (owners, `TBD` WIs, provisional markers).

The map is derived from the committed `cfg/catalog.json`, so it always
reflects the data that the site actually serves.

Usage:
  python3 scripts/gen_migration_map.py            # write docs/migration-map.md
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from uap_common import load_json, to_list  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]

# Compatibility-matrix remapping decisions (Decision 5): old ipName -> new IP
# Id, kept in sync with cfg/compatibility-matrix.json.
MATRIX_MAPPINGS = [
    ("CVE2", "cve2"),
    ("CV32E40", "cv32e40p"),
    ("CVA6", "cva6"),
    ("VSRV: Simple 32-bit RISC-V Linux-Capable Core", "vsrv"),
    ("Timing Channel Protection", "cva6-timing-channel"),
    ("Extend and Optimize CV32E20", "cve2"),
    ("RVB / RVP Standard Extensions support for CV32E40P core", "cv32e40p"),
    ("Extensions to the micro-architecture of CV32E40P core", "cv32e40p"),
    ("CV32A60X verification", "core-v-verif"),
    ("SCAIE-V custom instruction interface for CVA6", "scaie-v"),
    ("RVV coprocessor for CVA6", "ara"),
    ("CVA6", "cva6"),
    ("C-Trace", "c-trace"),
    ("DSP Ext", "riviera"),
    ("Co-processor Generator Tool", "openasip"),
    ("Hypervisor", "riscv-hypervisor"),
    ("TSN-Trace-Link", "tsn-trace-link"),
    ("GPIO", "gpio"),
    ("SPI Master", "spi-master"),
    ("UART 16750", "uart-16750"),
    ("Low-power IO DMA", "udma-core"),
    ("HPDcache", "hpdcache"),
    ("AXI LLC", "axi-llc"),
    ("CLIC", "clic"),
    ("AXI", "axi"),
    ("Heterogeneous Cluster Interconnect (HCI)", "hci"),
    ("SPEDE", "spede"),
    ("Reduced-Precision Matrix Multiplication Engine", "redmule"),
    ("eFPGA", "efpga"),
]

# Entries intentionally left as task labels: navigation lands on the Project
# view filtered by the matrix row's project, searching the old label.
MATRIX_UNMAPPED = [
    ("TGC", "No ips/tgc.json — The Good Core appears only inside the Moonlight subsystem (Scale4Edge)."),
    ("EMSA5", "No EMSA5 IP; an ISOLDE NXP-AT task label."),
    ("Low-End Processor EMSA5/TGC", "Task label spanning two processor families."),
    ("FPGA and Dual issue optimization", "Task label (CV32E40P micro-architecture work)."),
    ("Application Processors for Automotive", "Task label (CV32A60X work)."),
    ("CV-X-IF", "Interface family, not a single IP (see extension-interface-* IPs)."),
    ("CSR extension for TIP", "Task label (CV32E40X TIP work)."),
    ("Low-bitwidth mixed-precision integer arithmetic extensions for QNNs", "Task label (CV32E40P extensions)."),
    ("Light-Weight Co-processor", "Task label (CV32E20 co-processor)."),
    ("CVA6 ISA extension Coprocessor", "Task label (CVA6 co-processor)."),
    ("Custom Instructions for Automotive Applications", "Task label (CV32E40X extensions)."),
    ("Boundary Check extension based of CSRs", "Task label; the ISOLDE bcfi IP is a different (NXP) contribution."),
    ("LPDDR4X DRAM Controller", "No LPDDR IP exists in the migrated catalogue."),
]


def esc(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def wi_str(wi):
    return ", ".join(to_list(wi))


def main():
    catalog = load_json(ROOT / "cfg" / "catalog.json")
    out = []
    add = out.append

    ips = catalog["ips"]
    projects = catalog["projects"]
    n_tasks = sum(len(p.get("Tasks", [])) for p in projects.values())

    add("# Migration map: old per-project IP arrays → IP-centric layout")
    add("")
    add("Generated by `scripts/gen_migration_map.py` from `cfg/catalog.json`.")
    add("")
    add("The old data layout kept one array per project in `ips/<project>.json`")
    add("where most rows were actually *tasks* (Work Items), not IPs. The")
    add("migration split every row into (a) an independent IP in `ips/<id>.json`")
    add("and (b) a Task in `projects/<project>.json` referencing that IP. The old")
    add("array files are deleted; this page is the entry-by-entry record of that")
    add("split and of every case that still needs a human decision.")
    add("")
    add("How to read a task line: the old `ips/<project>.json` entry is identified")
    add("by its `TaskId` (the `WI` and `Title` are carried over verbatim); `IPs`")
    add("lists the new `ips/*.json` documents the task references.")
    add("")
    add(f"**Totals:** {len(ips)} IP documents, "
        f"{n_tasks} tasks across {len(projects)} project files.")
    add("")

    # --- Review checklists ------------------------------------------------
    owners_tbd = sorted(i for i, d in ips.items() if "TBD" in to_list(d.get("Owners")))
    prov_ips = sorted(
        i for i, d in ips.items()
        if "PROVISIONAL" in (d.get("Comment") or "")
    )
    tbd_wi = [(pid, t) for pid, p in projects.items() for t in p["Tasks"]
              if "TBD" in to_list(t.get("WI"))]
    tbd_partners = [(pid, t) for pid, p in projects.items() for t in p["Tasks"]
                    if "TBD" in to_list(t.get("Partners"))]

    add("## Review checklists")
    add("")
    add(f"### IP owners still `TBD` ({len(owners_tbd)})")
    add("")
    add("Per Decision 4, owners were **not** inferred from the old task Partners.")
    add("Fill these in case by case (`Owners` in `ips/<id>.json`, then regenerate")
    add("`cfg/catalog.json`):")
    add("")
    for ip_id in owners_tbd:
        d = ips[ip_id]
        add(f"- `{ip_id}` — {esc(d.get('Name',''))}")
    add("")
    add(f"### IP comments marked `PROVISIONAL` ({len(prov_ips)})")
    add("")
    add("Grouping, canonical URLs or owner guesses flagged during migration:")
    add("")
    for ip_id in prov_ips:
        add(f"- `{ip_id}`: {esc(ips[ip_id].get('Comment',''))}")
    add("")
    add(f"### Tasks with `WI: TBD` ({len(tbd_wi)})")
    add("")
    add("The source data carried no Work Item identifier:")
    add("")
    for pid, t in tbd_wi:
        add(f"- `{t['TaskId']}` ({esc(t.get('Title',''))})")
    add("")
    add(f"### Tasks with `Partners: TBD` ({len(tbd_partners)})")
    add("")
    for pid, t in tbd_partners:
        add(f"- `{t['TaskId']}` ({esc(t.get('Title',''))}): {esc(ips.get((to_list(t.get('IPs')) or ['?'])[0], {}).get('Name',''))}")
    add("")

    # --- Compatibility matrix ---------------------------------------------
    add("## Compatibility matrix remapping (Decision 5)")
    add("")
    add("Mapped `ipName` → IP `Id` (navigation lands on the IP view):")
    add("")
    add("| Old ipName | New ipName (IP Id) |")
    add("|---|---|")
    for old, new in MATRIX_MAPPINGS:
        add(f"| {esc(old)} | `{new}` |")
    add("")
    add("Unmapped (task labels — navigation lands on the Project view filtered")
    add("by the row's project, searching the old label):")
    add("")
    for old, why in MATRIX_UNMAPPED:
        add(f"- **{esc(old)}** — {why}")
    add("")

    # --- Per-project entry maps -------------------------------------------
    add("## Entry maps per project")
    add("")
    add("Old file: `ips/<project>.json` (deleted) → new tasks below, IPs under")
    add("`ips/`. Entries marked *duplicate* were kept because the source data")
    add("carried them twice with different content; merge after review.")
    add("")
    for pid in sorted(projects):
        proj = projects[pid]
        add(f"### {proj['Name']} (`projects/{pid}.json`, was `ips/{pid}.json`)")
        add("")
        add("| TaskId | WI | Title | IPs | Flags |")
        add("|---|---|---|---|---|")
        for t in proj["Tasks"]:
            flags = []
            if "TBD" in to_list(t.get("WI")):
                flags.append("WI TBD")
            if "TBD" in to_list(t.get("Partners")):
                flags.append("Partners TBD")
            comment = t.get("Comment") or ""
            if "PROVISIONAL" in comment:
                flags.append("PROVISIONAL")
            if "Duplicate" in comment or "duplicate" in comment:
                flags.append("duplicate")
            ips_cell = ", ".join(f"`{i}`" for i in to_list(t.get("IPs")))
            add(f"| `{t['TaskId']}` | {esc(wi_str(t.get('WI')))} | {esc(t.get('Title',''))} | {ips_cell} | {', '.join(flags)} |")
        add("")

    # --- IP inventory ------------------------------------------------------
    add("## IP inventory")
    add("")
    add(f"{len(ips)} independent IPs (`ips/<Id>.json`). `Tasks` counts the tasks")
    add("referencing the IP across all project files (0 is legitimate — Decision 3).")
    add("")
    task_count = {}
    for p in projects.values():
        for t in p["Tasks"]:
            for i in to_list(t.get("IPs")):
                task_count[i] = task_count.get(i, 0) + 1
    add("| IP Id | Name | Owners | Tasks |")
    add("|---|---|---|---|")
    for ip_id in sorted(ips):
        d = ips[ip_id]
        owners = ", ".join(to_list(d.get("Owners"))) or "—"
        add(f"| `{ip_id}` | {esc(d.get('Name',''))} | {esc(owners)} | {task_count.get(ip_id, 0)} |")
    add("")

    out_path = ROOT / "docs" / "migration-map.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {out_path} ({len(out)} lines).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
